#!/usr/bin/env node
/*
 * Pull the latest polls from Wikipedia and merge them into data/polls.js
 * (and data/polls.json, which the dashboard falls back to when a browser
 * cannot reach Wikipedia itself).
 *
 *   node scripts/update-polls.js            fetch, merge, write
 *   node scripts/update-polls.js --dry-run  fetch and report only
 *   node scripts/update-polls.js --race SEN-TX --race GOV-GA
 *   node scripts/update-polls.js --json-only  rewrite data/polls.json from data/polls.js, no fetch
 */
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const CONFIG = require('../js/config.js');
const MODEL = require('../js/model.js');
const WIKI = require('../js/wikipedia.js');

const ROOT = path.join(__dirname, '..');
const DATA_JS = path.join(ROOT, 'data', 'polls.js');
const DATA_JSON = path.join(ROOT, 'data', 'polls.json');
const USER_AGENT = '2026-midterm-forecast-dashboard/1.0 (https://github.com/danielwlee312/2026midtermelection)';

function parseArgs(argv) {
  const out = { dryRun: false, jsonOnly: false, races: [] };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--dry-run') out.dryRun = true;
    else if (argv[i] === '--json-only') out.jsonOnly = true;
    else if (argv[i] === '--race') out.races.push(argv[++i]);
  }
  return out;
}

function writeJson(data) {
  fs.writeFileSync(DATA_JSON, JSON.stringify({ meta: data.meta, polls: data.polls }, null, 1) + '\n');
}

function serialize(data) {
  const lines = data.polls.map((p) => '    ' + JSON.stringify(p));
  return [
    '/*',
    ' * Poll dataset used by the dashboard. Generated by scripts/update-polls.js',
    ' * from the hand-compiled snapshot (compiled ' + data.meta.compiled + ') plus rows read from',
    ' * Wikipedia poll tables (refreshed ' + data.meta.refreshed + ').',
    ' *',
    ' * Row fields',
    ' *   race      race id from js/config.js (SEN-xx, GOV-xx, HOUSE-US)',
    ' *   pollster  pollster as published; pollsterId = trusted-pollster id or null',
    ' *   start/end field dates (ISO). approx: true marks hand-compiled rows whose field',
    ' *             dates or sample size were not published; the release date stands in.',
    ' *   n, pop    sample size and population (LV likely, RV registered, A adults)',
    ' *   results   candidate last name -> percent',
    " *   partisan  'R' or 'D' when Wikipedia tags the poll as party-affiliated",
    " *   origin    'wikipedia' for rows read from Wikipedia; absent for hand-compiled rows",
    ' */',
    '(function (root, data) {',
    "  if (typeof module === 'object' && module.exports) module.exports = data;",
    '  else root.POLL_SNAPSHOT = data;',
    "})(typeof self !== 'undefined' ? self : this, {",
    '  meta: ' + JSON.stringify(data.meta) + ',',
    '  polls: [',
    lines.join(',\n'),
    '  ]',
    '});',
    ''
  ].join('\n');
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  delete require.cache[require.resolve(DATA_JS)];
  const current = require(DATA_JS);
  if (args.jsonOnly) {
    writeJson(current);
    console.log('Wrote ' + path.relative(ROOT, DATA_JSON) + ' (' + current.polls.length + ' polls)');
    return;
  }
  const races = args.races.length ? args.races.map((id) => {
    const r = MODEL.RACE_BY_ID[id];
    if (!r) throw new Error('Unknown race ' + id);
    return r;
  }) : CONFIG.RACES;

  console.log('Fetching ' + races.length + ' Wikipedia articles...');
  const res = await WIKI.fetchAll({
    races,
    concurrency: 4,
    headers: { 'User-Agent': USER_AGENT, 'Api-User-Agent': USER_AGENT },
    onProgress: (done, total, page) => {
      const trusted = page.polls.filter((p) => p.pollsterId).length;
      console.log(`[${String(done).padStart(2)}/${total}] ${page.ok ? 'ok  ' : 'FAIL'} ${page.race.padEnd(8)} ${String(page.polls.length).padStart(3)} polls (${trusted} trusted)  ${page.ok ? page.title : page.error}`);
    }
  });

  const ok = res.pages.filter((p) => p.ok);
  const merged = WIKI.mergePolls(current.polls, res.polls);
  const trustedAdded = merged.added.filter((p) => p.pollsterId);
  console.log('');
  console.log(`Pages read: ${ok.length}/${res.pages.length}`);
  console.log(`Polls found: ${res.polls.length} (${res.polls.filter((p) => p.pollsterId).length} from trusted pollsters)`);
  console.log(`New rows: ${merged.added.length} (${trustedAdded.length} trusted); updated rows: ${merged.updated.length}`);
  trustedAdded.forEach((p) => console.log(`  + ${p.race} ${p.pollster} ${p.start}..${p.end} ${JSON.stringify(p.results)}`));
  merged.updated.forEach((u) => console.log(`  ~ ${u.after.race} ${u.after.pollster} ${JSON.stringify(u.before.results)} -> ${JSON.stringify(u.after.results)}`));

  if (!ok.length) {
    console.error('No Wikipedia page could be read; leaving data files unchanged.');
    process.exitCode = 1;
    return;
  }

  const before = MODEL.run(current.polls, { sims: 4000 });
  const after = MODEL.run(merged.polls, { sims: 4000 });
  console.log('');
  console.log(`Senate control (Dem / no majority / GOP): ${pct(before.senate.probD)}/${pct(before.senate.probNeither)}/${pct(before.senate.probR)} -> ${pct(after.senate.probD)}/${pct(after.senate.probNeither)}/${pct(after.senate.probR)}`);

  if (args.dryRun) {
    console.log('Dry run: data files not written.');
    return;
  }
  const data = {
    meta: Object.assign({}, current.meta, {
      origin: 'snapshot+wikipedia',
      refreshed: res.fetchedAt,
      pagesRead: ok.length,
      pagesTotal: res.pages.length
    }),
    polls: merged.polls
  };
  fs.writeFileSync(DATA_JS, serialize(data));
  writeJson(data);
  console.log('Wrote ' + path.relative(ROOT, DATA_JS) + ' and ' + path.relative(ROOT, DATA_JSON));
}

function pct(p) { return Math.round(p * 100) + '%'; }

main().catch((err) => {
  console.error(err && err.stack || err);
  process.exitCode = 1;
});
